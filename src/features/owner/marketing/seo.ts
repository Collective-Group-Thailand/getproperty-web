import type { Metadata } from "next";

import { serverEnv } from "@/lib/env/server";
import { publicOrigin } from "@/lib/zones";
import { BRAND_NAME, BRAND_TAGLINE } from "@/ui/brand/config";
import type { MarketingPath } from "@/lib/zones/marketing";
import { getPathname } from "@/i18n/navigation";
import { routing, type Locale } from "@/i18n/routing";

/** The owner host's (the owner console's) public origin. */
export function ownerOrigin(): string {
  return publicOrigin(serverEnv().OWNER_HOST);
}

/**
 * Where the marketing pages are canonical, for canonical URLs, hreflang, robots and the sitemap: the platform's public
 * site (`MARKETING_HOST`) when there is one, else the owner host.
 */
export function marketingOrigin(): string {
  const env = serverEnv();
  return publicOrigin(env.MARKETING_HOST ?? env.OWNER_HOST);
}

/**
 * A link from a marketing page into the owner console (sign-in): absolute when the marketing pages are served on the
 * public site, so the visitor goes straight to the owner host instead of through its 308.
 */
export function ownerHref(path: string, locale: Locale): string {
  const pathname = getPathname({ href: path, locale });
  return serverEnv().MARKETING_HOST ? `${ownerOrigin()}${pathname}` : pathname;
}

/** The Open Graph card (1200 × 630, the founder's logo and the tagline), generated by `pnpm brand`. */
export function ogImage(origin: string) {
  return { url: `${origin}/brand/og-image.png`, width: 1200, height: 630, alt: `${BRAND_NAME} — ${BRAND_TAGLINE}` };
}

/** Indexable metadata of a marketing page: canonical, th/en alternates, Open Graph. */
export function marketingMetadata(
  path: MarketingPath | `/${string}`,
  locale: Locale,
  {
    title,
    description,
    type = "website",
    noindex = false,
  }: { title: string; description: string; type?: "website" | "article"; noindex?: boolean },
): Metadata {
  const origin = marketingOrigin();
  const url = (lang: Locale) => `${origin}${getPathname({ href: path, locale: lang })}`;
  return {
    title: { absolute: title },
    description,
    robots: { index: !noindex, follow: true },
    alternates: {
      canonical: url(locale),
      languages: Object.fromEntries([...routing.locales.map((lang) => [lang, url(lang)]), ["x-default", url("th")]]),
    },
    openGraph: {
      title,
      description,
      url: url(locale),
      siteName: "getproperty",
      locale: locale === "th" ? "th_TH" : "en_US",
      type,
      images: [ogImage(origin)],
    },
    twitter: { card: "summary_large_image", title, description, images: [ogImage(origin)] },
  };
}

/** The platform's LINE Official Account ("add friend" link), the public pages' sales channel; null when not configured. */
export function lineOaHref(): string | null {
  const id = serverEnv().NEXT_PUBLIC_LINE_OA_ID;
  return id ? `https://line.me/R/ti/p/${encodeURIComponent(id)}` : null;
}

/** A listing in the LINE Mini App (ask the owner, book a viewing, D-252); null when the LIFF id is not configured. */
export function liffRentHref(slug: string): string | null {
  const id = serverEnv().NEXT_PUBLIC_LIFF_ID;
  return id ? `https://liff.line.me/${encodeURIComponent(id)}/rent/${encodeURIComponent(slug)}` : null;
}

/** Opens a chat with the platform LINE OA with `text` typed in (LINE URL scheme `oaMessage`); null when not configured. */
export function lineOaMessageHref(text: string): string | null {
  const id = serverEnv().NEXT_PUBLIC_LINE_OA_ID;
  return id ? `https://line.me/R/oaMessage/${encodeURIComponent(id)}/?${encodeURIComponent(text)}` : null;
}
