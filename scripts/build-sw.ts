/**
 * Bundles the staff service worker (src/lib/pwa/sw/staff-sw.ts + Workbox) with esbuild into
 * `src/lib/pwa/generated/staff-sw.ts`, which `src/app/staff/sw.js/route.ts` serves at `/sw.js` on the
 * staff host (ADR-0007). The output is committed, like the design tokens: `--check` fails when it is
 * stale. The version is a hash of the bundle, so a changed worker replaces the old one's page cache.
 *
 *   pnpm sw          rebuild
 *   pnpm sw:check    CI drift check
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = resolve(ROOT, "src/lib/pwa/sw/staff-sw.ts");
const OUT = resolve(ROOT, "src/lib/pwa/generated/staff-sw.ts");

async function bundle(version: string): Promise<string> {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: "iife",
    target: "es2022",
    minify: true,
    legalComments: "none",
    define: { __SW_VERSION__: JSON.stringify(version), "process.env.NODE_ENV": '"production"' },
  });
  return result.outputFiles[0]!.text;
}

async function main() {
  // Two passes: the version is the hash of the bundle built without it.
  const unversioned = await bundle("0");
  const version = createHash("sha256").update(unversioned).digest("hex").slice(0, 12);
  const source = await bundle(version);
  const output = `/* GENERATED by scripts/build-sw.ts from src/lib/pwa/sw/staff-sw.ts — do not edit. */\nexport const STAFF_SW_VERSION = ${JSON.stringify(version)};\nexport const STAFF_SW_SOURCE = ${JSON.stringify(source)};\n`;
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== output) {
      console.error("src/lib/pwa/generated/staff-sw.ts is out of date — run `pnpm sw` and commit the result.");
      process.exit(1);
    }
    console.info(`service worker is up to date (${version})`);
    return;
  }
  writeFileSync(OUT, output);
  console.info(`wrote src/lib/pwa/generated/staff-sw.ts (${version}, ${source.length} bytes)`);
}

void main();
